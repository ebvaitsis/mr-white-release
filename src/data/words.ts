// ─── Build mixed and export ───────────────────────────────────────────────────

function buildMixed(cats: WordCategory[], label: string, labelEmoji: string): WordCategory {
  return { id: 'mixed', name: label, emoji: labelEmoji, pairs: cats.flatMap(c => c.pairs) };
}

// Mixed excludes football — separate arrays for mixed pool vs full category list
const EN_MIX: WordCategory[] = [EN_FOOD, EN_NATURE, EN_PLACES, EN_PROFESSIONS, EN_SPORTS, EN_ENTERTAINMENT, EN_OBJECTS];
const GR_MIX: WordCategory[] = [GR_FOOD, GR_NATURE, GR_PLACES, GR_GREECE, GR_PROFESSIONS, GR_SPORTS];

export const CATEGORIES_EN: WordCategory[] = [buildMixed(EN_MIX, 'Mixed (All)', '🎲'), ...EN_MIX, EN_FOOTBALL];
export const CATEGORIES_GR: WordCategory[] = [buildMixed(GR_MIX, 'Μικτή (Όλα)', '🎲'), ...GR_MIX, GR_FOOTBALL];

export function getCategories(language: 'en' | 'gr'): WordCategory[] {
  return language === 'gr' ? CATEGORIES_GR : CATEGORIES_EN;
}

export function getRandomPair(categoryId: string, language: 'en' | 'gr') {
  const cats = getCategories(language);
  const cat = cats.find(c => c.id === categoryId) ?? cats[0];
  return cat.pairs[Math.floor(Math.random() * cat.pairs.length)];
}